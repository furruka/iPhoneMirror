// The HID report descriptor the desktop publishes to iOS, and the report layout
// that goes with it.
//
// These bytes are a copy of BluetoothHidMouseService.ReportMap in the WPF
// project and must stay identical to it: an incompatible change invalidates
// existing pairings, which is what BluetoothHidProtocol.ReportMapVersion exists
// to track. They are duplicated rather than extracted because the WPF project
// does not build on Linux, so extracting them there would mean editing a file
// this side cannot compile; that extraction belongs in a change verified by
// Windows CI.

